export function deriveNlProvince(postcode: string): string {
  const digits = postcode.replace(/\D/g, "").slice(0, 4)
  if (digits.length < 4) return "zh"

  const num = parseInt(digits, 10)
  for (const [from, to, province] of RANGES) {
    if (num >= from && num <= to) return province
  }

  return "zh"
}
